-- Fixed version: the first attempt at this migration created policies
-- that call is_manager()/my_department_id() BEFORE those functions
-- existed, which Postgres validates at CREATE POLICY time — hence
-- "function public.is_manager() does not exist". This version creates
-- every function before anything that references it, and uses
-- if-not-exists / drop-if-exists / create-or-replace throughout so
-- it's safe to run again even if the earlier attempt partially applied.

-- 1. Departments table + seed.
create table if not exists public.departments (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

insert into public.departments (name)
values ('Website'), ('Graphics'), ('Pre Order')
on conflict (name) do nothing;

alter table public.departments enable row level security;

drop policy if exists "departments_select_all_authenticated" on public.departments;
create policy "departments_select_all_authenticated" on public.departments
  for select using (auth.role() = 'authenticated');

-- 2. profiles gains 'manager' role and department_id — must exist
--    before we define any function that references department_id.
alter table public.profiles drop constraint if exists profiles_role_check;
alter table public.profiles add constraint profiles_role_check
  check (role in ('super_admin', 'manager', 'staff'));
alter table public.profiles add column if not exists department_id bigint
  references public.departments(id);

-- 3. tasks gains department routing and a task-nature field.
alter table public.tasks add column if not exists department_id bigint
  references public.departments(id);
alter table public.tasks add column if not exists task_type text default 'other';
alter table public.tasks drop constraint if exists tasks_task_type_check;
alter table public.tasks add constraint tasks_task_type_check
  check (task_type in ('upload', 'seo', 'image', 'price_change', 'other'));

-- 4. Helper functions — created now, since everything below depends
--    on them and both need the columns added in steps 2-3 to exist.
create or replace function public.is_manager()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role in ('super_admin', 'manager')
  );
$$;
grant execute on function public.is_manager() to authenticated;

create or replace function public.my_department_id()
returns bigint
language sql
security definer
set search_path = public
stable
as $$
  select department_id from public.profiles where id = auth.uid();
$$;
grant execute on function public.my_department_id() to authenticated;

-- 5. task_assignees junction table.
create table if not exists public.task_assignees (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  assigned_to uuid not null references auth.users(id),
  fulfilled_by uuid references auth.users(id),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (task_id, assigned_to)
);

alter table public.task_assignees enable row level security;

drop policy if exists "task_assignees_select_authenticated" on public.task_assignees;
create policy "task_assignees_select_authenticated" on public.task_assignees
  for select using (auth.role() = 'authenticated');

drop policy if exists "task_assignees_insert_authenticated" on public.task_assignees;
create policy "task_assignees_insert_authenticated" on public.task_assignees
  for insert with check (auth.role() = 'authenticated');

drop policy if exists "task_assignees_update_authenticated" on public.task_assignees;
create policy "task_assignees_update_authenticated" on public.task_assignees
  for update using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

drop policy if exists "task_assignees_delete_admin_or_manager" on public.task_assignees;
create policy "task_assignees_delete_admin_or_manager" on public.task_assignees
  for delete using (public.is_super_admin() or public.is_manager());

-- 6. Widen profiles visibility: self, admin, manager, or same department.
drop policy if exists "profiles_select_own_or_admin" on public.profiles;
drop policy if exists "profiles_select_own_admin_manager_or_dept" on public.profiles;
create policy "profiles_select_own_admin_manager_or_dept" on public.profiles
  for select using (
    auth.uid() = id
    or public.is_super_admin()
    or public.is_manager()
    or department_id = public.my_department_id()
  );

-- 7. Auto-completion trigger.
create or replace function public.recompute_task_completion()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target_task_id bigint;
  all_done boolean;
begin
  target_task_id := coalesce(new.task_id, old.task_id);

  select bool_and(completed_at is not null) into all_done
  from public.task_assignees
  where task_id = target_task_id;

  if all_done is true then
    update public.tasks set workflow_status = 'done'
      where id = target_task_id and workflow_status <> 'done';
  elsif all_done is false then
    update public.tasks set workflow_status = 'in_progress'
      where id = target_task_id and workflow_status = 'done';
  end if;

  return coalesce(new, old);
end;
$$;

drop trigger if exists task_assignees_completion_trigger on public.task_assignees;
create trigger task_assignees_completion_trigger
after insert or update or delete on public.task_assignees
for each row execute function public.recompute_task_completion();
