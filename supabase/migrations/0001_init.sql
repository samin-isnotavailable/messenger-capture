-- Historical snapshot of the "Messenger Ops Tracker" schema as it existed
-- before the Taskapture upgrade. This documents where the project came
-- from — it is NOT meant to be run against the live project, which
-- already has this table. Running it will fail with "relation already
-- exists" (42P07), and that's expected/correct.

create table public.tasks (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  task text,
  status text,
  user_id uuid,
  done_by_email text,
  done_by uuid,
  priority text default 'medium',
  due_date date,
  source_url text
);

alter table public.tasks enable row level security;

create policy "allow_select_own" on public.tasks
  for select using (auth.uid() = user_id);
create policy "allow_select" on public.tasks
  for select using (true);
create policy "allow_all_authenticated_select" on public.tasks
  for select using (true);
create policy "allow_all_authenticated_insert" on public.tasks
  for insert with check (true);
create policy "allow_update_authenticated" on public.tasks
  for update using (true) with check (true);
create policy "allow_delete_admin_only" on public.tasks
  for delete using (auth.uid() = '7540a37a-dd17-4a9a-9688-1a29922beacd'::uuid);
create policy "Enable delete for users based on user_id" on public.tasks
  for delete using (auth.uid() = user_id);
